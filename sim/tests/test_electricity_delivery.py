"""Electricity is generated at a busbar and delivered at a meter, and the line between costs something. A three-entry chain
(a generator, a delivery with a loss, a consumer) priced by `priced_goods_table`: the delivered energy costs more than the
generated by the loss and the plant, rises with the loss, falls when a lower-loss delivery node is held, and a dearer
generator passes into a consumer by that consumer's electrical share. The tests assert relationships, never a dated price.
The real entries' data and physics are test_electricity_delivery_data."""
QUICK_TOPIC = True

import copy
import unittest

from sim.prices import prices as price_solver

GATE = "three_wire_node"
LOSSY = 1.25
LOW_LOSS = 1.05


def entries(generator_hours=10.0, loss=LOSSY):
    return {
        "generator": {"outputs": {"generated_mj": 100.0}, "inputs": {}, "labour_hours": {"electrician": generator_hours},
                      "requires_node": None},
        "two_wire": {"outputs": {"delivered_mj": 1.0}, "inputs": {"generated_mj": loss}, "labour_hours": {"electrician": 0.5},
                     "requires_node": None},
        "three_wire": {"outputs": {"delivered_mj": 1.0}, "inputs": {"generated_mj": LOW_LOSS},
                       "labour_hours": {"electrician": 0.5}, "requires_node": GATE},
        "smelter": {"outputs": {"metal_kg": 1.0}, "inputs": {"delivered_mj": 4.0}, "labour_hours": {"electrician": 2.0},
                    "requires_node": None},
    }


DOCUMENT = {"wage_rates_denarii_per_hour": {"labourer": {"rate": 2.0}, "electrician": {"rate": 4.0}}, "money_per_labour_hour": 2.0}


def solve(production, held=()):
    price_solver.reset_caches_for_tests()
    goods, _provenance = price_solver.priced_goods_table(set(held), DOCUMENT, production_entries=production)
    return goods


class DeliveryPriceTests(unittest.TestCase):
    def test_delivered_energy_costs_more_than_generated_by_the_loss_and_the_plant(self):
        goods = solve(entries(), held=())
        self.assertGreater(goods["delivered_mj"], goods["generated_mj"] * LOW_LOSS)

    def test_delivered_price_rises_with_the_loss(self):
        self.assertGreater(solve(entries(loss=1.5))["delivered_mj"], solve(entries(loss=1.25))["delivered_mj"])

    def test_holding_the_lower_loss_node_lowers_the_delivered_price(self):
        self.assertLess(solve(entries(), held={GATE})["delivered_mj"], solve(entries(), held=set())["delivered_mj"])

    def test_a_dearer_generator_raises_the_delivered_price_and_a_consumer_by_no_more_than_its_electrical_share(self):
        base = solve(entries())
        dear = solve(entries(generator_hours=10000.0))
        self.assertGreater(dear["delivered_mj"], base["delivered_mj"])
        self.assertGreater(dear["metal_kg"], base["metal_kg"])
        electrical_share = base["delivered_mj"] * 4.0 / base["metal_kg"]
        bound = 1.0 + electrical_share * (dear["delivered_mj"] / base["delivered_mj"] - 1.0)
        self.assertLessEqual(dear["metal_kg"] / base["metal_kg"], bound + 1e-9)


if __name__ == "__main__":
    unittest.main()
